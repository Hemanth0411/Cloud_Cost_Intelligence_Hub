'use client';

import { Check, Info, Loader2, Sparkles } from 'lucide-react';
import { Badge } from '@/components/ui/badge';
import { Card } from '@/components/ui/card';
import { ANALYSIS_STEPS, type InsightReportState } from '@/hooks/use-insight-report';
import { cn } from '@/lib/utils';
import { TypewriterText } from './typewriter-text';

function DiffChip({ state }: { state: InsightReportState }) {
  const diff = state.lastDiff;
  if (!diff) return null;
  const none = diff.added + diff.updated + diff.removed === 0;
  return (
    <Badge variant={none ? 'secondary' : 'default'} role="status">
      {none ? 'No changes since the last analysis' : `${diff.added} new · ${diff.updated} updated · ${diff.removed} removed`}
    </Badge>
  );
}

export function AiSummaryCard({ state }: { state: InsightReportState }) {
  const analyzing = state.status === 'analyzing';
  const report = state.bundle?.report ?? null;

  return (
    <Card className="relative overflow-hidden">
      <div className="pointer-events-none absolute inset-x-0 top-0 h-1 bg-gradient-to-r from-ateneo via-bronze to-khaki" aria-hidden />
      <div className="space-y-4 p-3 sm:p-3">
        <div className="flex flex-wrap items-center gap-3">
          <span className="flex h-9 w-9 items-center justify-center rounded-lg bg-ateneo text-cream">
            <Sparkles className="h-5 w-5" aria-hidden />
          </span>
          <div className="mr-auto">
            <h2 className="text-base font-semibold leading-tight">AI summary</h2>
            <p className="text-xs text-muted-foreground">{report ? `${report.subject} · ${report.periodPhrase}` : 'Preparing analysis'}</p>
          </div>
          <Badge variant="outline" className="gap-1.5" title="Generated by deterministic templates from the mock dataset. No external AI model is called, and no endpoint backs this page.">
            <Info className="h-3 w-3" aria-hidden /> Simulated AI · rule-based
          </Badge>
        </div>

        {analyzing ? (
          <ol className="space-y-2" aria-live="polite" aria-label="Analysis progress">
            {ANALYSIS_STEPS.map((label, index) => {
              const done = state.step > index;
              const current = state.step === index;
              return (
                <li key={label} className={cn('flex items-center gap-2.5 text-sm', !done && !current && 'text-muted-foreground/60', done && 'text-muted-foreground')}>
                  {done ? <Check className="h-4 w-4 text-success" aria-hidden /> : current ? <Loader2 className="h-4 w-4 animate-spin text-ateneo" aria-hidden /> : <span className="h-4 w-4 rounded-full border" aria-hidden />}
                  {label}
                </li>
              );
            })}
          </ol>
        ) : (
          report && (
            <p className="text-[15px] leading-relaxed">
              <TypewriterText text={report.headline} animationId={state.animationId} />
            </p>
          )
        )}

        {!analyzing && report && (
          <div className="flex flex-wrap items-center gap-x-4 gap-y-2 border-t pt-3 text-xs text-muted-foreground">
            <span className="tabular-nums">
              Analyzed {report.stats.rowsAnalyzed.toLocaleString('en-US')} cost records · {report.stats.anomaliesConsidered} anomalies · {report.stats.opportunities} opportunities
            </span>
            {state.generatedAt && (
              <span className="tabular-nums">Last analyzed {state.generatedAt.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', second: '2-digit' })}</span>
            )}
            <DiffChip state={state} />
          </div>
        )}
      </div>
    </Card>
  );
}
