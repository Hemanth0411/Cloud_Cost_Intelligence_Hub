import type { Severity } from '@/types/domain';
import type { SimulatedAlert } from './build';

interface Template {
  severity: Severity;
  title: (account: string) => string;
  message: (account: string) => string;
}

/** Every simulated alert is labelled as such in its message; nothing here reflects real spend. */
const TEMPLATES: readonly Template[] = [
  {
    severity: 'high',
    title: (a) => `Daily cost threshold exceeded in ${a}`,
    message: (a) => `Simulated event: a daily-cost rule would have fired for ${a}. No real threshold was crossed.`,
  },
  {
    severity: 'medium',
    title: (a) => `Budget 80% reached for ${a}`,
    message: (a) => `Simulated event: ${a} would have reached 80% of its monthly budget. This is a demo notification.`,
  },
  {
    severity: 'critical',
    title: (a) => `Unusual usage burst in ${a}`,
    message: (a) => `Simulated event: a sudden usage burst in ${a}. Generated by the demo, not detected from the data.`,
  },
  {
    severity: 'low',
    title: (a) => `Sync completed with warnings for ${a}`,
    message: (a) => `Simulated event: a billing sync for ${a} would have finished with warnings. Demo only.`,
  },
];

/** Cycles through the templates and the available accounts, so each press adds something different. */
export function createSimulatedAlert(counter: number, accountNames: readonly string[], now: Date): SimulatedAlert {
  const template = TEMPLATES[counter % TEMPLATES.length] ?? TEMPLATES[0];
  const account = accountNames.length > 0 ? (accountNames[counter % accountNames.length] ?? 'an account') : 'an account';
  return {
    id: `sim-${counter}`,
    severity: template?.severity ?? 'medium',
    title: template?.title(account) ?? 'Simulated alert',
    message: template?.message(account) ?? 'Simulated event.',
    timestamp: `${now.toISOString().slice(0, 19)}Z`,
    accountId: null,
  };
}

export function createTestAlert(counter: number, channels: readonly string[], now: Date): SimulatedAlert {
  return {
    id: `sim-${counter}`,
    severity: 'low',
    title: 'Test notification',
    message: `Simulated test: this would be delivered via ${channels.length > 0 ? channels.join(', ') : 'no channels'}. Nothing was actually sent.`,
    timestamp: `${now.toISOString().slice(0, 19)}Z`,
    accountId: null,
  };
}
